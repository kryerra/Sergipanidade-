const FULL_VIEWBOX = '50 158 385 175';

export function Logo({
  variant = 'light',
  width,
  height,
  iconOnly = false,
  showSlogan = false,
  className = '',
}: LogoProps) {
  const sloganColor =
    variant === 'dark' ? 'rgba(255,255,255,0.65)' :
    variant === 'teal' ? 'rgba(13,115,119,0.7)' :
    'rgba(26,26,26,0.55)';

  const fillColor =
    variant === 'dark' ? '#FFFFFF' :
    variant === 'teal' ? '#0D7377' :
    '#1A1A1A';

  if (iconOnly) {
    const iconWidth = width ?? 44;
    const iconHeight = height ?? iconWidth;
    return (
      <svg
        viewBox={ICON_VIEWBOX}
        width={iconWidth}
        height={iconHeight}
        className={className}
        style={{
          display: 'block',
          flexShrink: 0,
          width: typeof iconWidth === 'number' ? `${iconWidth}px` : iconWidth,
          height: typeof iconHeight === 'number' ? `${iconHeight}px` : iconHeight,
          fill: variant === 'dark' ? '#FFFFFF' : variant === 'teal' ? '#0D7377' : '#1A1A1A',
        }}
        preserveAspectRatio="xMidYMid meet"
      >
        {ICON_PATHS}
      </svg>
    );
  }

  const w = width ?? 145;
  const h = height ?? 64;

  return (
    <div className={`flex flex-col items-center ${className}`} style={{ display: 'inline-flex', flexDirection: 'column', alignItems: 'center' }}>
      <svg
        viewBox={FULL_VIEWBOX}
        width={w}
        height={h}
        style={{
          display: 'block',
          flexShrink: 0,
          width: typeof w === 'number' ? `${w}px` : w,
          height: typeof h === 'number' ? `${h}px` : h,
          fill: fillColor,
        }}
        preserveAspectRatio="xMidYMid meet"
      >
        {ICON_PATHS}
        {TEXT_PATHS}
      </svg>
      {showSlogan && (
        <span
          style={{
            marginTop: 4,
            fontSize: typeof w === 'number' ? Math.round((w as number) * 0.072) : 13,
            color: sloganColor,
            fontStyle: 'italic',
            letterSpacing: '0.06em',
            whiteSpace: 'nowrap',
          }}
        >
          Vem ser gente da gente!
        </span>
      )}
    </div>
  );
}